"""Emit every DAT_/PTR_ symbol as a LIVE LVALUE at its own address.

THE BUG THIS REPLACES. The first version of this generator resolved each symbol
to the word sitting at its address IN THE ROM IMAGE and emitted that as a
constant:

    #define DAT_01ff8a98 ((void *)(uintptr_t)0x027E02A4u)   /* wrong */

That is a snapshot of boot-time memory frozen into the source. 1,527 symbols
were emitted this way. Any store the game makes to that variable would be
invisible to every later read, and the symbol is not even assignable, so a
plain `DAT_x = 0` would not compile. It reads plausibly, which is exactly what
made it dangerous.

The whole reason the DS regions are mapped at their native addresses is so that
a DS address IS a host address. So a Ghidra global is simply the memory at its
address:

    #define DAT_01ff8a98 (*(undefined4 **)(uintptr_t)0x01FF8A98u)

Reads see what was last written. Writes land where the hardware would put them.
No snapshot, nothing frozen.

CHOOSING THE SHAPE. The .c bodies do not carry Ghidra's type for a global, so
the shape is taken from how the corpus actually uses each symbol - which is
evidence, not preference:

    (*DAT_x)(...)  called      -> pointer to a function returning a value
    *DAT_x         dereferenced-> pointer to 32-bit data
    otherwise                  -> 32-bit data

Where a symbol is used two ways the more capable shape wins and the symbol is
reported, so the disagreement is visible rather than silently resolved.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "recomp" / "decomp" / "gen"
DIRS = [ROOT / "out" / "ghidra" / "decomp" / "c",
        ROOT / "out" / "ghidra" / "decomp_itcm" / "c"]

SYM = r"(?:DAT|PTR|UNK|_DAT|__DAT|uRam|iRam|bRam|cRam)_?[0-9a-fA-F]{8}"
ANY = re.compile(r"\b(%s)\b" % SYM)
# A LEADING `*` IS ONLY A DEREFERENCE IF NOTHING COULD BE MULTIPLIED BY IT.
# The first version used a bare `\*\s*SYM`, which read the multiplication in
# `iVar1 * DAT_x` as a dereference and typed 13 plainly-integer symbols as
# pointers. The lookbehind rejects a preceding operand.
DEREF = re.compile(r"(?<![A-Za-z0-9_)\]])\*\s*(%s)\b" % SYM)
# Indexing is the other way a body says "this is a pointer".
# casts are matched back in explicitly.
# preceding `)`, which is right for `(a+b)*DAT_x` and wrong for a cast, so
# ...but `(int)*DAT_x` IS a dereference. The lookbehind above rejects a
CASTDEREF = re.compile(r"\([A-Za-z_][A-Za-z0-9_ ]*\**\)\s*\*\s*(%s)\b" % SYM)
INDEX = re.compile(r"\b(%s)\s*\[" % SYM)
CALL = re.compile(r"\(\s*\*\s*(%s)\s*\)\s*\(" % SYM)


def main() -> int:
    used: set[str] = set()
    deref: set[str] = set()
    called: set[str] = set()
    for d in DIRS:
        if not d.exists():
            continue
        for p in d.glob("*.c"):
            t = p.read_text(encoding="utf-8", errors="replace")
            used.update(ANY.findall(t))
            deref.update(DEREF.findall(t))
            deref.update(INDEX.findall(t))
            deref.update(CASTDEREF.findall(t))
            called.update(CALL.findall(t))

    out = [
        "/* Generated by tools/gen_dat.py - do not edit.",
        " *",
        " * Each symbol is the LIVE MEMORY at its address, not a boot-time",
        " * snapshot. See tools/gen_dat.py for why that distinction matters.",
        " */",
        "#ifndef LSW2_DECOMP_DAT_H",
        "#define LSW2_DECOMP_DAT_H",
        '#include "ghidra_types.h"',
        "",
    ]
    n_call = n_ptr = n_val = 0
    for name in sorted(used):
        addr = int(re.search(r"[0-9a-fA-F]{8}$", name).group(0), 16)
        if name in called:
            out.append("#define %s (*(undefined4 (**)())(uintptr_t)0x%08Xu)"
                       % (name, addr))
            n_call += 1
        elif name in deref:
            out.append("#define %s (*(undefined4 **)(uintptr_t)0x%08Xu)"
                       % (name, addr))
            n_ptr += 1
        else:
            out.append("#define %s (*(undefined4 *)(uintptr_t)0x%08Xu)"
                       % (name, addr))
            n_val += 1
    out += ["", "#endif"]
    (GEN / "dat.h").write_text("\n".join(out) + "\n", encoding="utf-8")

    print("symbols            %d" % len(used))
    print("  called           %d" % n_call)
    print("  dereferenced     %d" % n_ptr)
    print("  plain data       %d" % n_val)
    both = (called & deref)
    if both:
        print("  used both ways   %d  (function-pointer shape wins)" % len(both))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
