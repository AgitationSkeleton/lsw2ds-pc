"""Extract the FreeBIOS images from ndsrecomp's generated C embed.

WHY THIS IS NEEDED. The runner links four BIOS banks unconditionally: the two
retail ones and the two FreeBIOS ones. Recompiling the FreeBIOS pair needs the
image binaries at `third_party/freebios/drastic_bios_arm{9,7}.bin` - and in the
framework checkout here that submodule is EMPTY, so those files do not exist.

The bytes are still present, though, as C arrays in the generated embed
`vendor/freebios/freebios_images.cpp`, which the runner compiles in for its
`--freebios` mode. Reading them back out reproduces the images exactly.

THE HASHES ARE THE POINT. Both are pinned in the framework's own documentation
and checked by the runner at startup. This script refuses to write a file whose
SHA-1 does not match, because a silently-wrong BIOS would produce a game that
misbehaves in ways that look like translation bugs - which is the single most
expensive kind of mistake this project can make.

FreeBIOS is Copyright (c) 2013 Gilead Kutnick, BSD-2-Clause. Nothing is copied
into this repository; the extracted images land in out/work/ and are
regenerated by port/build.sh.

Usage:  python tools/extract_freebios.py <path-to-ndsrecomp>
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import sys

# (symbol, output name, expected size, expected sha1)
IMAGES = [
    ("nds_freebios9", "drastic_bios_arm9.bin", 4096,
     "b85d6afdbf65d87c9ab11d4e7fb5ecfd6192ccf8"),
    ("nds_freebios7", "drastic_bios_arm7.bin", 16384,
     "eaab9b21610978f05a0eb14a9c8ff345698f56a2"),
]


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__.strip().splitlines()[-1])
        return 2
    framework = pathlib.Path(sys.argv[1])
    embed = framework / "vendor/freebios/freebios_images.cpp"
    if not embed.exists():
        print("no FreeBIOS embed at %s" % embed)
        return 1

    out = pathlib.Path(__file__).resolve().parents[1] / "out/work/ndsrecomp/freebios"
    out.mkdir(parents=True, exist_ok=True)
    src = embed.read_text(encoding="utf-8", errors="replace")

    failures = 0
    for sym, name, size, want in IMAGES:
        m = re.search(re.escape(sym) + r"\[\d+\]\s*=\s*\{(.*?)\};", src, re.S)
        if not m:
            print("%s: symbol not found in the embed" % sym)
            failures += 1
            continue
        data = bytes(int(b, 16)
                     for b in re.findall(r"0x([0-9A-Fa-f]{2})", m.group(1)))
        got = hashlib.sha1(data).hexdigest()
        if len(data) != size or got != want:
            print("%s: REFUSING to write - %d bytes sha1 %s, expected %d and %s"
                  % (name, len(data), got, size, want))
            failures += 1
            continue
        (out / name).write_bytes(data)
        print("%s: %d bytes, sha1 %s verified" % (name, len(data), got))

    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
