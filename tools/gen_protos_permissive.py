"""Generate cross-function declarations that cannot contradict a definition.

THE PROBLEM THIS SOLVES, WHICH IS NOT A DECOMPILATION PROBLEM.

Ghidra decompiles each function in isolation. It types FUN_02068e34's own
definition from the body it can see, and it types every CALL to FUN_02068e34
from the register traffic at the call site. Those two guesses disagree
constantly - 954 "too few arguments", 559 "too many", 1196 "invalid use of void
expression" across the Bounty Hunter closure. Every one is Ghidra contradicting
Ghidra about a signature. NONE of them is a function Ghidra failed to decompile;
the bodies are all there.

Guessing which side is right, 4,907 times, would be exactly the kind of
mechanical rewriting this port has already been burned by.

SO NEITHER SIDE IS OVERRULED. The definition in each .c file is left alone and
treated as authoritative for that function. Every OTHER function is declared
K&R-style - `undefined4 FUN_x();` - which in C means "returns a value, argument
list unspecified". A call site may then pass whatever ARM actually passed and
use or discard r0, and the compiler checks neither, because at the ARM level
neither is checkable: r0 holds a return value whether or not the callee meant
it to.

A file must not see the permissive declaration of the function it defines, or
the two conflict. Each declaration is therefore guarded, and the build defines
the guard for the file's own function.

This is not a workaround around bad data. It is the accurate statement of what
the machine code guarantees: a BL passes registers and returns r0.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "recomp" / "decomp" / "gen"
DIRS = [ROOT / "out" / "ghidra" / "decomp" / "c",
        ROOT / "out" / "ghidra" / "decomp_itcm" / "c"]

# Every name a body may call: Ghidra's FUN_, its thunks, and func_0x - the form
# it uses when it resolved a call target but created no function there.
NAME = re.compile(r"\b(FUN_[0-9a-fA-F]{8}|thunk_FUN_[0-9a-fA-F]{8}|func_0x[0-9a-fA-F]{8})\b")


def main() -> int:
    names: set[str] = set()
    defined: set[str] = set()
    for d in DIRS:
        if not d.exists():
            continue
        for p in d.glob("*.c"):
            defined.add(p.stem)
            names.update(NAME.findall(p.read_text(encoding="utf-8",
                                                  errors="replace")))

    # func_0xADDR and FUN_ADDR are the same address in two notations. Keep both
    # spellings declared; the linker resolves them via the alias below.
    out = [
        "/* Generated by tools/gen_protos_permissive.py - do not edit.",
        " * See that file for why these are argument-unspecified.",
        " */",
        "#ifndef LSW2_DECOMP_PROTOS_H",
        "#define LSW2_DECOMP_PROTOS_H",
        '#include "ghidra_types.h"',
        "",
    ]
    aliases = []
    for n in sorted(names):
        guard = "LSW2_SELF_" + n
        out.append("#ifndef %s" % guard)
        out.append("undefined4 %s();" % n)
        out.append("#endif")
        if n.startswith("func_0x"):
            target = "FUN_" + n[7:].lower()
            if target in defined:
                aliases.append((n, target))
    out.append("")
    out.append("/* func_0xADDR is Ghidra's spelling for a call to an address it")
    out.append(" * resolved but never made a function of. Same address, same")
    out.append(" * code - so the same symbol. */")
    for n, target in aliases:
        out.append("#define %s %s" % (n, target))
    out += ["", "#endif"]
    (GEN / "protos.h").write_text("\n".join(out) + "\n", encoding="utf-8")

    print("functions referenced anywhere : %d" % len(names))
    print("functions with a body         : %d" % len(defined))
    print("func_0x aliases resolved      : %d" % len(aliases))
    print("unresolved func_0x            : %d"
          % len([n for n in names if n.startswith("func_0x")
                 and "FUN_" + n[7:].lower() not in defined]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
