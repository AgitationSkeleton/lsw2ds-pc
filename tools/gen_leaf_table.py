"""Build the table of leaf functions to run through both engines.

A LEAF IS THE HONEST PLACE TO START. Ghidra records each function's callees in a
`// calls:` line, and a function with none is a pure computation: it reads its
arguments and whatever globals it touches, writes its result, and calls nothing.
That makes any disagreement between the interpreter and the compiled C the
translation's fault and nothing else's - no callee to blame, no ordering, no
hardware.

578 of the closure's 1,510 compiled functions are leaves. That is a real corpus,
not a spot check.

The signature is taken from the definition line, because it decides how the
function may safely be driven: a pointer parameter is handed a scratch block, a
scalar is handed a value. Handing a scalar to a pointer parameter would have the
function write through whatever integer it was given, which is how a differential
harness corrupts the thing it is measuring.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
WORK = ROOT / "out" / "work" / "closure_build"
GEN = ROOT / "recomp" / "decomp" / "gen"

CALLS = re.compile(r"^// calls:(.*)$", re.M)
# The definition: return type, name, parameter list, at the end of a line.
DEFN = re.compile(
    r"^([A-Za-z_][A-Za-z0-9_ \t\*]*?)\b(FUN_[0-9a-fA-F]{8})\s*\(([^)]*)\)\s*$",
    re.M)


# HOW WIDE THE RETURN VALUE ACTUALLY IS.
#
# A function declared `bool` sets only AL; the rest of EAX keeps whatever was
# there. Comparing all 32 bits against the interpreter's r0 then reports a
# disagreement that is not one - FUN_02067d20 returned 0x01 from the
# interpreter and 0xDDDDE601 from the decomp, and the low byte, the only part
# either side promised anything about, matched exactly.
#
# So the comparison is masked to the width the definition declares. This is a
# fix to the HARNESS, not a tolerance: a narrow return that differs in its
# declared bits is still a disagreement.
NARROW = {
    "bool": 1, "byte": 1, "char": 1, "undefined1": 1, "uint8_t": 1, "u8": 1,
    "sbyte": 1, "short": 2, "ushort": 2, "undefined2": 2, "uint16_t": 2,
    "u16": 2,
}


def return_bytes(ret: str) -> int:
    """The number of low bytes the return type actually defines."""
    if "*" in ret:
        return 4
    return NARROW.get(ret.strip().split()[-1] if ret.strip() else "", 4)


def kinds_of(args: str) -> str:
    """'p' for a pointer parameter, 'v' for a scalar. '' for none."""
    args = args.strip()
    if not args or args == "void":
        return ""
    out = []
    for a in args.split(","):
        out.append("p" if "*" in a else "v")
    return "".join(out)


def main() -> int:
    files = [l.strip() for l in
             (WORK / "files.txt").read_text(encoding="utf-8").splitlines()
             if l.strip()]
    rows = []
    skipped_varargs = 0
    for f in files:
        p = ROOT / f
        if not p.exists():
            continue
        if not (WORK / "obj" / (p.stem + ".o")).exists():
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        m = CALLS.search(text)
        if not m or m.group(1).strip():
            continue  # not a leaf
        d = DEFN.search(text)
        if not d:
            continue
        ret, name, args = d.group(1).strip(), d.group(2), d.group(3)
        if name != p.stem:
            continue  # the file defines something other than its own name
        if "..." in args:
            skipped_varargs += 1
            continue
        kinds = kinds_of(args)
        if len(kinds) > 4:
            continue  # beyond the register-argument convention
        returns = 0 if ret == "void" else 1
        rows.append((int(name[4:], 16), name, kinds, returns,
                     return_bytes(ret)))

    rows.sort()
    out = [
        "/* Generated by tools/gen_leaf_table.py - do not edit.",
        " * See that file for why leaves are the right differential corpus.",
        " */",
        "#ifndef LSW2_LEAF_TABLE_H",
        "#define LSW2_LEAF_TABLE_H",
        "",
        "typedef struct {",
        "    uint32_t addr;",
        "    const char *name;",
        "    const char *kinds; /* 'p' pointer, 'v' scalar, in order */",
        "    int returns;       /* 0 if the definition says void */",
        "    int ret_bytes;     /* low bytes the return type defines */",
        "    void *fn;",
        "} leaf_entry;",
        "",
    ]
    for _addr, name, _k, _r, _w in rows:
        out.append("undefined4 %s();" % name)
    out.append("")
    out.append("static const leaf_entry LEAVES[] = {")
    for addr, name, kinds, returns, width in rows:
        out.append('    {0x%08Xu, "%s", "%s", %d, %d, (void *)%s},'
                   % (addr, name, kinds, returns, width, name))
    out.append("};")
    out.append("#define LEAF_COUNT (sizeof(LEAVES) / sizeof(LEAVES[0]))")
    out += ["", "#endif"]
    (GEN / "leaf_table.h").write_text("\n".join(out) + "\n", encoding="utf-8")

    by_kind = {}
    for _a, _n, k, _r, _w in rows:
        by_kind[len(k)] = by_kind.get(len(k), 0) + 1
    print("leaf functions in the table %d" % len(rows))
    for n in sorted(by_kind):
        print("  %d parameter(s)            %d" % (n, by_kind[n]))
    print("  with a return value        %d" % sum(r[3] for r in rows))
    print("  narrower than 32 bits      %d"
          % sum(1 for r in rows if r[3] and r[4] < 4))
    if skipped_varargs:
        print("  skipped (varargs)          %d" % skipped_varargs)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
