#!/bin/sh
# Build the isolated recomp: the closure, the host layer, and the runner.
#
# THE PORT IS BUILT 32-BIT, AND THAT IS NOT A PREFERENCE.
#
# The approach rests on mapping the DS regions at their native addresses so a DS
# pointer is a host pointer and 1,500 decompiled functions run with no source
# rewriting. On x86-64 that holds for the VALUE and breaks on the WIDTH: a DS
# pointer is four bytes, a host pointer is eight. The decompiled C loads pointers
# straight out of DS memory -
#
#     UNRECOVERED_JUMPTABLE = DAT_020ca450;
#     piVar1 = *(int **)(param_1 + 8);
#
# - and on a 64-bit build each of those reads four bytes of whatever sits next
# door. It is not theoretical: FUN_020ca434 crashed on `mov 0x20ca44c,%rax`,
# an eight-byte load of a four-byte DS pointer, on main()'s very first call.
#
# 529 such loads across 200 files, plus 1,364 pointer-shaped DAT symbols. Roughly
# 1,900 sites, every one silently wrong. Fixing them individually is precisely
# the mechanical rewrite of decompiled code this port refuses to do, and it would
# still not be enough - the values live in tables the game builds at runtime.
#
# A 32-bit build makes the whole class correct by construction. Nothing to
# rewrite, nothing to remember, nothing to get wrong later.
set -e
cd "$(dirname "$0")/.."

# ONE BUILD AT A TIME. Two builds raced twice while this port was being brought
# up, interleaving their object writes and their shared results file, and
# produced counts that looked exactly like a regression - "compiled 2288"
# against a 4,909-file corpus. A stale lock from a killed build is cleared by
# deleting out/work/closure_build/build.lock.
mkdir -p out/work/closure_build
if ! mkdir out/work/closure_build/build.lock 2>/dev/null; then
    echo "another build is already running (out/work/closure_build/build.lock)"
    echo "if that is stale, kill any surviving cc1.exe/gcc.exe FIRST, then"
    echo "remove it - deleting the lock while the old build is still compiling"
    echo "starts a second one, and the two interleave their objects and their"
    echo "shared results file. That has happened twice."
    exit 1
fi
trap 'rmdir out/work/closure_build/build.lock 2>/dev/null || true' EXIT

CC=/c/msys64/mingw32/bin/gcc.exe
export PATH="/c/msys64/mingw32/bin:$PATH"
OUT=out/work/closure_build
INC="-I recomp/decomp/include -I recomp/decomp/gen"
PRE="-include ghidra_types.h -include ghidra_intrinsics.h -include labels.h -include unresolved.h"
FLAGS="-O0 -mregparm=3 -std=gnu11 -fno-strict-aliasing -fpermissive -w"

HOSTFLAGS="-O0 -std=gnu11 -fno-strict-aliasing -fpermissive -w"

mkdir -p "$OUT/obj"

# The CP15 spellings Ghidra uses, collected from the sources rather than chased
# one link error at a time.
python tools/gen_cp15_names.py > "$OUT/gen_cp15.log"; tail -2 "$OUT/gen_cp15.log"
python tools/gen_labels.py > "$OUT/gen_labels.log"; head -1 "$OUT/gen_labels.log"
# A FAILED BUILD MUST NOT LEAVE A RUNNABLE EXECUTABLE BEHIND.
#
# The host layer failed to compile, the link never happened, run_game.exe from
# the previous build was still sitting there, and the run that followed
# executed it and reported results - for the wrong binary, with no indication
# that anything was stale. The build printed its error and exited 1; that was
# not enough, because the next command in the chain did not care.
#
# Removing it up front means a broken build produces a missing file, which
# fails loudly, instead of an old file, which lies quietly.
rm -f "$OUT/run_game.exe"

# SELF-HEAL THE HEREDOC TRAP BEFORE COMPILING ANYTHING. Writing C through a
# shell heredoc turns `\n` inside a string literal into a real newline, which
# is a compile error that names a line forty lines from anything related. It
# has now broken the build five times, and the fifth cost a full rebuild to
# discover - the link failed, the old executable was still on disk, and the
# run that followed silently measured the PREVIOUS build.
#
# The repair is unambiguous and it announces what it touched, so this heals the
# mistake without hiding it. The real fix is still not to do it: use an editor
# tool for anything containing an escape.
python tools/fix_split_literals.py recomp/decomp/src/*.c

python tools/gen_unresolved.py > "$OUT/gen_unres.log"; tail -1 "$OUT/gen_unres.log"
# MUST run every build. It was generated by hand and went stale the moment
# a function was added to config/host_overrides.txt, and the result was a
# duplicate definition at link time after a full 40-minute rebuild.
python tools/gen_unfaithful_wrappers.py > "$OUT/gen_unfaithful.log"; tail -2 "$OUT/gen_unfaithful.log"
python tools/gen_trace_wrappers.py > "$OUT/gen_trace.log"; head -1 "$OUT/gen_trace.log"
python tools/gen_veneers.py > "$OUT/gen_veneers.log"; head -2 "$OUT/gen_veneers.log"
python tools/gen_call_patches.py > "$OUT/gen_patches.log"; head -2 "$OUT/gen_patches.log"
# Runs AFTER the call patches and reads what they left, so the two compose.
python tools/gen_syntax_patches.py > "$OUT/gen_syntax.log"; tail -3 "$OUT/gen_syntax.log"
# Runs last of the patch stages and reads what they left.
python tools/gen_irq_patches.py > "$OUT/gen_irq.log"; tail -4 "$OUT/gen_irq.log"
python tools/gen_swi_patches.py > "$OUT/gen_swi.log"; tail -3 "$OUT/gen_swi.log"
# Indirect calls whose arguments Ghidra dropped. Runs alongside the SWI
# transcriptions and reads what the earlier patch stages left.
python tools/gen_vtable_patches.py > "$OUT/gen_vtable.log"; tail -4 "$OUT/gen_vtable.log"
# Conditional returns Ghidra called jump tables. Mechanical, driven by
# the instructions, and it refuses anything it cannot prove.
python tools/gen_condreturn_patches.py > "$OUT/gen_condret.log"; tail -4 "$OUT/gen_condret.log"
# Stack locals the ARM had adjacent and C does not have to.
python tools/gen_adjacent_locals_patches.py > "$OUT/gen_adj.log"; tail -4 "$OUT/gen_adj.log"

# A stamp of everything that would change how a source compiles. If a .o is
# newer than both its source and this stamp, recompiling it cannot change the
# result - and a full sweep of 4,909 files is ten minutes that iteration cannot
# afford to spend on unchanged code.
cat recomp/decomp/include/*.h recomp/decomp/gen/protos.h     recomp/decomp/gen/cp15_names.h config/*.txt "$0" 2>/dev/null > "$OUT/.stamp.new"
if ! cmp -s "$OUT/.stamp.new" "$OUT/.stamp" 2>/dev/null; then
    mv "$OUT/.stamp.new" "$OUT/.stamp"
    echo "  build inputs changed - everything will be recompiled"
else
    rm -f "$OUT/.stamp.new"
fi

# EVERY DECOMPILED FUNCTION IS BUILT, NOT JUST THE STATICALLY REACHABLE ONES.
#
# The closure in config/recomp_inventory.json is what static analysis can see.
# It cannot see an indirect call, and the game is full of them - the very first
# thing main() does reaches 0x020CA79C through a function pointer built at
# runtime. That function is decompiled, has a proper prologue and is 184 bytes
# long; it simply is not in any static call graph, so the port stopped with
# "no host function exists there".
#
# An address the game can call has to be present. Whether a static tool could
# predict the call is not the game's problem. So everything with a decompiled
# body is compiled and enters the dispatch table, and the closure goes back to
# being what it always should have been - a way of REPORTING scope, not a way of
# deciding what exists.
#
# The ARM7 is deliberately excluded: it is a different processor, and its work
# reaches the ARM9 through IPC rather than through calls.
python - <<'PY' > "$OUT/files.txt"
import pathlib
for d in (pathlib.Path('out/ghidra/decomp/c'), pathlib.Path('out/ghidra/decomp_itcm/c')):
    if d.exists():
        for p in sorted(d.glob('FUN_*.c')):
            print(p.as_posix())
PY
echo "  $(wc -l < "$OUT/files.txt") decompiled functions to build"

# THE BUILD CLOSES OVER ACTUAL REFERENCES, NOT OVER THE INVENTORY.
# Ghidra records a call to an address it never made a function of as
# `func_0xADDR`, and those never became closure edges - so the inventory's 1,555
# is a floor. Each pass compiles what is listed, asks the linker what is still
# undefined, and adds any of those that have a decompiled body. See
# tools/close_build.py.
pass_no=0
while : ; do
pass_no=$((pass_no + 1))
echo "--- the closure, pass $pass_no ---"
: > "$OUT/results.txt"
xargs -a "$OUT/files.txt" -P 8 -I{} sh -c '
  f="{}"; base=$(basename "$f" .c)
  if grep -qx "$base" config/excluded_functions.txt 2>/dev/null; then
    rm -f out/work/closure_build/obj/"$base".o; echo EXCLUDED; exit 0; fi
  if grep -qx "$base" config/host_overrides.txt 2>/dev/null; then
    rm -f out/work/closure_build/obj/"$base".o; echo OVERRIDE; exit 0; fi
  # A tail-call veneer is generated by the host so that it forwards its
  # arguments; Ghidra typed it (void) and dropped them. See gen_veneers.py.
  if grep -qx "$base" config/veneers.txt 2>/dev/null; then
    rm -f out/work/closure_build/obj/"$base".o; echo VENEER; exit 0; fi
  rename=""
  if grep -qx "$base" config/unfaithful_wrapped.txt 2>/dev/null; then
    rename="-D${base}=${base}_unfaithful"
  elif grep -qx "$base" config/traced_active.txt 2>/dev/null; then
    rename="-D${base}=${base}_traced"
  fi
  # THE SOURCE IS CHOSEN BEFORE IT IS DATE-CHECKED, and the order is the bug.
  # A file whose dropped call arguments were restored from the instructions is
  # compiled from the patched copy; out/ghidra keeps the original so the two can
  # be diffed. Doing this AFTER the freshness test meant the test compared the
  # object against the ORIGINAL, found it newer, and skipped the rebuild - so
  # the patch existed on disk and never reached the binary.
  if [ -f out/work/patched/"$base".c ]; then f=out/work/patched/"$base".c; fi
  obj=out/work/closure_build/obj/"$base".o
  if [ -f "$obj" ] && [ "$obj" -nt "$f" ] &&      [ "$obj" -nt out/work/closure_build/.stamp ] &&      [ "$obj" -nt recomp/decomp/gen/dat/"$base".h ]; then
    echo "OK"; exit 0
  fi
  guards=$(grep -a "^$base " out/work/selfguards.txt | cut -d" " -f2-)
  if /c/msys64/mingw32/bin/gcc.exe -c -O0 -mregparm=3 -std=gnu11 -w -fno-strict-aliasing \
       -fpermissive $guards $rename \
       -I recomp/decomp/include -I recomp/decomp/gen \
       -include ghidra_types.h -include ghidra_intrinsics.h \
       -include labels.h -include unresolved.h -include protos.h -include dat/"$base".h \
       "$f" -o out/work/closure_build/obj/"$base".o 2>/dev/null
  then echo "OK"; else echo "NO $f"; fi
' >> "$OUT/results.txt"

ok=$(grep -ac '^OK' "$OUT/results.txt" || true)
no=$(grep -ac '^NO' "$OUT/results.txt" || true)
ov=$(grep -ac '^OVERRIDE' "$OUT/results.txt" || true)
ex=$(grep -ac '^EXCLUDED' "$OUT/results.txt" || true)
grep -a '^NO ' "$OUT/results.txt" | awk '{print $2}' > "$OUT/failed.txt" || true
echo "  compiled $ok   failed $no   host-replaced $ov   excluded $ex"

echo "  compiled $ok   failed $no   host-replaced $ov   excluded $ex" > /dev/null

# Ask the linker what is still missing, and close over it.
# The shims the decompiled code calls share its convention; the files that
# Windows and the C runtime call keep theirs. See LSW2_ARMCALL / LSW2_HOSTCALL.
for s in ghidra_support host_overrides unfaithful_wrappers trace_wrappers veneers; do
    $CC -c $FLAGS $INC $PRE "recomp/decomp/src/$s.c" -o "$OUT/support_$s.o"
done
for s in map arm7 io diag unresolved vram host_threads; do
    $CC -c $HOSTFLAGS $INC $PRE "recomp/decomp/src/$s.c" -o "$OUT/support_$s.o"
done
rm -f "$OUT/support_untranslated.o"   # it must not vote on what is missing
ls "$OUT"/obj/*.o "$OUT"/support_*.o 2>/dev/null | xargs -n 200 nm > "$OUT/nm.txt" 2>/dev/null
awk '$2=="T"{s=$3; sub(/^_/,"",s); print s}' "$OUT/nm.txt" | sort -u > "$OUT/defined.txt"
awk '$1=="U"{s=$2; sub(/^_/,"",s); print s}' "$OUT/nm.txt" | sort -u > "$OUT/undef.txt"
comm -23 "$OUT/undef.txt" "$OUT/defined.txt" > "$OUT/missing.txt"
set +e
python tools/close_build.py > "$OUT/close.log"
closed=$?
set -e
tail -2 "$OUT/close.log"
if [ "$closed" -ne 10 ]; then break; fi
if [ "$pass_no" -ge 8 ]; then echo "  not converging - stopping"; break; fi
done

echo "--- the host layer ---"
# The shims the decompiled code calls share its convention; the files that
# Windows and the C runtime call keep theirs. See LSW2_ARMCALL / LSW2_HOSTCALL.
for s in ghidra_support host_overrides unfaithful_wrappers trace_wrappers veneers; do
    $CC -c $FLAGS $INC $PRE "recomp/decomp/src/$s.c" -o "$OUT/support_$s.o"
done
for s in map arm7 io diag unresolved vram host_threads; do
    $CC -c $HOSTFLAGS $INC $PRE "recomp/decomp/src/$s.c" -o "$OUT/support_$s.o"
done

echo "--- the dispatch table, from what actually linked ---"
rm -f "$OUT/support_untranslated.o"
ls "$OUT"/obj/*.o "$OUT"/support_*.o | xargs -n 200 nm > "$OUT/nm.txt" 2>/dev/null
awk '$2=="T"{s=$3; sub(/^_/,"",s); print s}' "$OUT/nm.txt" | sort -u > "$OUT/defined.txt"
awk '$1=="U"{s=$2; sub(/^_/,"",s); print s}' "$OUT/nm.txt" | sort -u > "$OUT/undef.txt"
comm -23 "$OUT/undef.txt" "$OUT/defined.txt" > "$OUT/missing.txt"
python tools/gen_stubs.py > "$OUT/gen_stubs.log"; head -1 "$OUT/gen_stubs.log"
python tools/gen_dispatch.py > "$OUT/gen_dispatch.log"; head -1 "$OUT/gen_dispatch.log"
$CC -c $FLAGS $INC $PRE recomp/decomp/src/untranslated.c -o "$OUT/support_untranslated.o"
$CC -c $HOSTFLAGS $INC $PRE recomp/decomp/src/dispatch.c -o "$OUT/support_dispatch.o"
$CC -c $HOSTFLAGS $INC $PRE recomp/decomp/src/run_game.c -o "$OUT/support_run_game.o"

echo "--- link ---"
ls "$OUT"/obj/*.o > "$OUT/objs.txt"
for s in map intrinsics ghidra_support host_overrides unfaithful_wrappers \
         arm7 io diag unresolved vram host_threads trace_wrappers veneers untranslated dispatch run_game; do
    echo "$OUT/support_$s.o" >> "$OUT/objs.txt"
done
rm -f "$OUT/run_game.exe"
$CC @"$OUT/objs.txt" -Wl,--disable-dynamicbase -o "$OUT/run_game.exe"
echo "  $(wc -l < "$OUT/objs.txt") objects -> $OUT/run_game.exe"
