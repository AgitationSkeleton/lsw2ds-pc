"""Emit an aborting stub for every closure function Ghidra could not translate.

WHY STUBS AND NOT SILENCE. 43 of the closure's 1,555 functions do not compile:
Ghidra lost a stack slot, dropped a jump-table label, or emitted a sub-field
access on a scalar. Their callers still reference them, so the port cannot link
without something at those names.

That something ABORTS AND NAMES ITSELF. A stub returning 0 would link just as
well and would then quietly produce a wrong game - a turret that does not build,
a camera that lurches - with nothing pointing at the cause. This project has
already spent months on defects of exactly that shape.

So the game runs until it actually needs one of these, and then says which.
"""

from __future__ import annotations

import pathlib

NL = chr(92) + "n"  # a literal backslash-n inside the generated C string


def main() -> int:
    root = pathlib.Path(__file__).resolve().parents[1]
    work = root / "out" / "work" / "closure_build"

    missing = [l.strip() for l in
               (work / "missing.txt").read_text(encoding="utf-8",
                                                errors="replace").splitlines()
               if l.strip().startswith(("FUN_", "thunk_FUN_", "func_0x"))]

    reason = {}
    for line in (work / "perfile.txt").read_text(encoding="utf-8",
                                                 errors="replace").splitlines():
        if "|" not in line:
            continue
        why, path = line.split("|", 1)
        reason[pathlib.Path(path).stem] = why

    out = [
        "/* Generated by tools/gen_stubs.py - do not edit.",
        " *",
        " * One aborting stub per closure function Ghidra could not translate.",
        " * Each names itself and why. See the generator for the reasoning.",
        " */",
        '#include "ghidra_intrinsics.h"',
        "",
    ]
    for name in sorted(missing):
        why = reason.get(name) or reason.get(name.replace("thunk_", "")) \
            or "Ghidra produced no usable C"
        why = why.replace('"', "'")
        out.append("undefined4 %s(void) {" % name)
        out.append('    lsw2_die("lsw2: %s is not translated (%s).");'
                   % (name, why))
        out.append("}")
        out.append("")

    (root / "recomp" / "decomp" / "src" / "untranslated.c").write_text(
        "\n".join(out), encoding="utf-8")

    print("stubs emitted %d" % len(missing))
    by = {}
    for n in missing:
        by.setdefault(reason.get(n, "Ghidra produced no usable C"), []).append(n)
    for k, v in sorted(by.items(), key=lambda kv: -len(kv[1])):
        print("  %-40s %d" % (k[:40], len(v)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
