"""Collect every CP15 spelling Ghidra uses, so they stop arriving one link error at a time.

Ghidra names a coprocessor access after the register it decoded, so the set of
names is whatever the cartridge happens to touch: Control, Domain_Access_Control,
Translation_table_base_0, Invalidate_Entire_Data_cache, and so on. Thirteen
appear across the corpus. Chasing them individually as the linker finds them is
pointless work.

They are RECORDED AND NOT OBEYED. The host owns the memory layout - every DS
region is mapped where the DS puts it - so acting on an MMU or cache
configuration write would move memory out from under the port for no benefit.
The values are kept so a later read returns what was written.

ONE NAME IS EXCLUDED, AND IT MATTERS. Wait_for_interrupt is not configuration:
on hardware it halts the core until an interrupt arrives, and the game uses it
to wait for VBlank. Turning it into a recorded no-op would make that wait return
immediately, which is precisely the "host answers not-ready forever" spin this
project has already been bitten by. It has a real implementation in
ghidra_support.c and must not be generated over.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
NAMES = re.compile(r"\bcoproc_(moveto|movefrom)_([A-Za-z0-9_]+)\b")

# Names with real behaviour, which this must not generate a no-op for.
EXCLUDE = {"Wait_for_interrupt"}


def main() -> int:
    found = {}
    for d in ("out/ghidra/decomp/c", "out/ghidra/decomp_itcm/c",
              "out/ghidra/decomp_arm7/c"):
        p = ROOT / d
        if not p.exists():
            continue
        for f in p.glob("*.c"):
            text = f.read_text(encoding="utf-8", errors="replace")
            for kind, name in NAMES.findall(text):
                found[(kind, name)] = found.get((kind, name), 0) + 1

    out = [
        "/* Generated by tools/gen_cp15_names.py - do not edit.",
        " *",
        " * Every coprocessor spelling Ghidra emits anywhere in the corpus,",
        " * recorded rather than obeyed. See the generator for why, and for why",
        " * Wait_for_interrupt is deliberately absent.",
        " */",
        "#ifndef LSW2_CP15_NAMES_H",
        "#define LSW2_CP15_NAMES_H",
        '#include "ghidra_types.h"',
        "",
        "/* Each register gets an index rather than a name. Comparing strings",
        " * meant a libc call on every coprocessor access, across the boundary",
        " * between the port's convention and the host's - and the port faulted",
        " * inside strcmp on the very first one. An index needs neither. */",
        "uint32_t lsw2_cp15_slot(unsigned slot, uint32_t value, int write);",
        "",
    ]
    # ONE SLOT PER REGISTER, not per access. Reading Control and writing
    # Control are the same register; giving them separate slots would make a
    # read-modify-write silently lose the bits it just read.
    slot_of = {}
    for _kind, name in sorted(found):
        if name in EXCLUDE:
            continue
        if name not in slot_of:
            slot_of[name] = len(slot_of)
    emitted = 0
    for (kind, name), _n in sorted(found.items()):
        if name in EXCLUDE:
            continue
        if kind == "moveto":
            out.append('#define coproc_moveto_%s(v) '
                       'lsw2_cp15_slot(%du, (uint32_t)(v), 1)'
                       % (name, slot_of[name]))
        else:
            out.append('#define coproc_movefrom_%s() '
                       'lsw2_cp15_slot(%du, 0, 0)' % (name, slot_of[name]))
        emitted += 1
    out += ["", "#endif"]
    (ROOT / "recomp/decomp/gen/cp15_names.h").write_text(
        "\n".join(out) + "\n", encoding="utf-8")

    print("CP15 spellings in the corpus %d" % len(found))
    print("  generated                  %d" % emitted)
    print("  hand-implemented           %d  (%s)"
          % (len(found) - emitted, ", ".join(sorted(EXCLUDE))))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
