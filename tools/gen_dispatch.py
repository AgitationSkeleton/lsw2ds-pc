"""Build the DS-address -> host-function table.

THE PROBLEM IT SOLVES, WHICH IS THE CENTRAL ONE FOR THIS WHOLE APPROACH.

Mapping the DS regions at their native addresses makes a DS DATA pointer a valid
host pointer, and that is what lets 1,500 decompiled functions run with no source
rewriting. It does nothing for a DS CODE pointer. The bytes at 0x020C99FC are ARM
instructions; jumping there on x86 is a crash, and the decompiled C jumps there
constantly:

    UNRECOVERED_JUMPTABLE = DAT_020ca450;   /* = 0x020C99FC */
    (*UNRECOVERED_JUMPTABLE)();

93 of the closure's 1,555 functions - 6% - make an indirect call of some kind:
vtables, callbacks, state-machine dispatch, and tail-call veneers. Every one of
them holds a DS address.

Rewriting 93 files to route through a lookup is exactly the mechanical
transformation this port refuses to do, and it would not even be sufficient: the
pointers are stored in memory the game builds at runtime, so the value is not
visible at the call site.

So nothing is rewritten. The regions are mapped NON-EXECUTABLE, an attempt to
call a DS address raises a hardware fault carrying that exact address, and the
handler looks the address up here and continues at the host function. The
arguments are already in the right registers - the C compiler put them there for
the indirect call it thought it was making - and the return address is already
on the stack, so the call and its return work unmodified.

This table is what makes that lookup possible.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
WORK = ROOT / "out" / "work" / "closure_build"
GEN = ROOT / "recomp" / "decomp" / "gen"

FUN = re.compile(r"^FUN_([0-9a-fA-F]{8})$")

# Names whose own address is not the address in the name. A veneer is named for
# what it jumps TO, so it has to be placed at the addresses it actually occupies.
EXTRA = {
    "thunk_FUN_0205e540": [0x0205E80C, 0x0205E818],
}


def main() -> int:
    defined = [l.strip() for l in
               (WORK / "defined.txt").read_text(encoding="utf-8").splitlines()
               if l.strip()]

    entries = []
    for name in defined:
        m = FUN.match(name)
        if m:
            entries.append((int(m.group(1), 16), name))
    for name, addrs in EXTRA.items():
        if name in defined:
            for a in addrs:
                entries.append((a, name))

    entries.sort()
    # A duplicate address would make the lookup ambiguous; the last one wins and
    # it is reported rather than silently chosen.
    seen, rows, dupes = set(), [], []
    for addr, name in entries:
        if addr in seen:
            dupes.append((addr, name))
            continue
        seen.add(addr)
        rows.append((addr, name))

    out = [
        "/* Generated by tools/gen_dispatch.py - do not edit.",
        " * See that file for why an indirect call needs this at all.",
        " */",
        "#ifndef LSW2_DISPATCH_TABLE_H",
        "#define LSW2_DISPATCH_TABLE_H",
        "",
        "typedef struct {",
        "    uint32_t ds_addr;",
        "    void *host_fn;",
        "} lsw2_dispatch_entry;",
        "",
    ]
    for _a, name in rows:
        out.append("undefined4 %s();" % name)
    out.append("")
    out.append("/* Sorted by address, so the lookup is a binary search. */")
    out.append("static const lsw2_dispatch_entry LSW2_DISPATCH[] = {")
    for addr, name in rows:
        out.append("    {0x%08Xu, (void *)%s}," % (addr, name))
    out.append("};")
    out.append("#define LSW2_DISPATCH_COUNT "
               "(sizeof(LSW2_DISPATCH) / sizeof(LSW2_DISPATCH[0]))")
    out += ["", "#endif"]
    (GEN / "dispatch_table.h").write_text("\n".join(out) + "\n",
                                          encoding="utf-8")

    print("host functions in the dispatch table %d" % len(rows))
    if dupes:
        print("  duplicate addresses skipped        %d" % len(dupes))
        for a, n in dupes[:5]:
            print("    0x%08X %s" % (a, n))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
