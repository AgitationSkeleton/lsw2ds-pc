"""Make the unfaithful functions LOUD without editing a line of decompiled C.

THE PROBLEM. 70 closure functions read processor state Ghidra could not account
for - `unaff_r4`, `in_r3`, `extraout_r1`. They compile, they link, and they run,
and what they read is whatever the C compiler happened to leave in an
uninitialised local. Proven, not suspected: FUN_01ff8404 returns 0 from the real
instructions and 4 from the decompiled C.

Every one is a genuine BL target, so every one is a real function the game
calls. And the cause is usually not decompiler weakness but calling convention:
0x01FF8404 opens with `subs r9, r9, r4`, so its arguments arrive in r4 and r9
rather than r0-r3 - hand-written assembly in ITCM, where the hot maths lives.

WHY NOT JUST ABORT. That is what the untranslated 43 do, and it is right for
them: they have no body at all. These have a body that is wrong in some paths
and quite possibly right in others, and stopping the port dead at 70 points
would prevent finding out which. The information is worth more than the
enforcement.

WHY NOT EDIT THE SOURCES. Because "do not edit translated code" is the rule that
keeps this port honest, and a hand-tweaked decompiled body is indistinguishable
from an improvised one six months later.

SO: THE ORIGINAL IS RENAMED AT COMPILE TIME. The decompiled file is compiled
with -DFUN_x=FUN_x_unfaithful, which renames its definition and nothing else,
and a generated wrapper takes the real name. The wrapper records that the game
reached this function and calls straight through. Callers are untouched, the
decompiled source is untouched, and at exit the port reports exactly which
unfaithful functions the game actually entered.

That turns "70 functions might be wrong" into a short list of the ones that
actually run - which is the list worth translating by hand.
"""

from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def main() -> int:
    unfaithful = [l.strip() for l in
                  (ROOT / "out/work/closure_build/unfaithful.txt")
                  .read_text(encoding="utf-8").splitlines() if l.strip()]
    overrides = set()
    ov = ROOT / "config/host_overrides.txt"
    if ov.exists():
        overrides = {l.strip() for l in ov.read_text(encoding="utf-8").splitlines()
                     if l.strip() and not l.startswith("#")}
    # A function the host already replaces needs no wrapper - it is not
    # compiled from the decomp at all.
    names = [n for n in unfaithful if n not in overrides]

    (ROOT / "config/unfaithful_wrapped.txt").write_text(
        "# Functions whose decompiled C reads processor state Ghidra could not\n"
        "# account for. Compiled under a renamed symbol and reached through a\n"
        "# wrapper that records the call. See tools/gen_unfaithful_wrappers.py.\n"
        + "\n".join(names) + "\n", encoding="utf-8")

    out = [
        "/* Generated by tools/gen_unfaithful_wrappers.py - do not edit.",
        " *",
        " * One wrapper per function whose decompiled body reads registers",
        " * Ghidra could not account for. Each records that the game reached it",
        " * and calls the original, which was compiled under a renamed symbol.",
        " */",
        '#include "ghidra_intrinsics.h"',
        "",
        "typedef undefined4 (*lsw2_any)(undefined4, undefined4, undefined4,",
        "                               undefined4);",
        "",
        "unsigned lsw2_unfaithful_hits[%d];" % max(1, len(names)),
        "const char *const lsw2_unfaithful_names[] = {",
    ]
    for n in names:
        out.append('    "%s",' % n)
    out += [
        "};",
        "const unsigned lsw2_unfaithful_count = %d;" % len(names),
        "",
    ]
    for n in names:
        out.append("undefined4 %s_unfaithful();" % n)
    out.append("")
    for i, n in enumerate(names):
        out.append("undefined4 %s(undefined4 a, undefined4 b, undefined4 c,"
                   % n)
        out.append("                        undefined4 d) {")
        out.append("    lsw2_unfaithful_hits[%d]++;" % i)
        out.append("    return ((lsw2_any)%s_unfaithful)(a, b, c, d);" % n)
        out.append("}")
        out.append("")

    out += [
        "/* What the game ACTUALLY reached. The 70 are a static worry; this is",
        " * the real list, and it is the one worth translating by hand. */",
        "LSW2_HOSTCALL void lsw2_report_unfaithful(FILE *to) {",
        "    (void)to;  /* stderr is unusable here - see diag.c */",
        "    unsigned reached = 0;",
        "    for (unsigned i = 0; i < lsw2_unfaithful_count; i++) {",
        "        if (lsw2_unfaithful_hits[i]) reached++;",
        "    }",
        "    if (!reached) {",
        "        lsw2_diagf(\"no unfaithful function was reached\\n\");",
        "        return;",
        "    }",
        "    lsw2_diagf(\"%u of %u unfaithful functions were reached:\\n\",",
        "            reached, lsw2_unfaithful_count);",
        "    for (unsigned i = 0; i < lsw2_unfaithful_count; i++) {",
        "        if (lsw2_unfaithful_hits[i]) {",
        "            lsw2_diagf(\"  %-16s %u call(s)\\n\",",
        "                    lsw2_unfaithful_names[i], lsw2_unfaithful_hits[i]);",
        "        }",
        "    }",
        "}",
        "",
    ]
    (ROOT / "recomp/decomp/src/unfaithful_wrappers.c").write_text(
        "\n".join(out), encoding="utf-8")

    print("unfaithful functions        %d" % len(unfaithful))
    print("  already host-replaced     %d" % (len(unfaithful) - len(names)))
    print("  wrapped and recorded      %d" % len(names))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
