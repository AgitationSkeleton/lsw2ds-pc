"""Turn Ghidra's decompiled C into something a compiler will accept.

THE APPROACH, AND WHY IT CAN WORK AT ALL. Ghidra emits bodies full of raw
pointer arithmetic on DS addresses:

    *(uint *)(iVar3 + 0x14) = *(uint *)(iVar3 + 0x14) & 0xffff0fff | 0xf000;

On a normal host those are wild pointers. But every DS region can be mapped at
its NATIVE address on this machine - ITCM, main RAM, DTCM, shared WRAM, palette,
VRAM and OAM all reserve successfully at 0x01FF8000, 0x02000000, 0x027E0000,
0x03000000, 0x05000000, 0x06000000 and 0x07000000. With the address space laid
out that way, a DS pointer IS a host pointer and the decompiled code runs
unchanged. No source rewriting, no accessor pass, no chance of a transformation
introducing a bug the original did not have.

WHAT THIS GENERATES

  ghidra_types.h  the types Ghidra emits - undefined1/2/4, uint, byte, code -
                  and the DS region constants.
  protos.h        a prototype for every function, taken from its OWN definition
                  line in its own file, so a call site cannot disagree with the
                  definition.
  dat.h           every DAT_/PTR_ symbol the bodies reference.

THE DAT_ PROBLEM, STATED HONESTLY. Ghidra names a literal-pool word by its POOL
ADDRESS and then uses the symbol with whatever type it inferred - sometimes as a
value (`uVar2 = DAT_x;`) and sometimes as a pointer (`*DAT_x = 1;`). The .c file
does not record which. A single macro cannot serve both, so each symbol is
emitted according to how the bodies actually use it: dereferenced anywhere means
pointer-shaped, otherwise value-shaped. Where a symbol is used both ways the
file is reported rather than guessed at.

Usage:  python tools/gen_decomp_build.py
"""

from __future__ import annotations

import json
import re
import struct
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT / "out" / "ghidra" / "decomp" / "c"
DECOMP_ITCM = ROOT / "out" / "ghidra" / "decomp_itcm" / "c"
OUT = ROOT / "recomp" / "decomp"
GEN = OUT / "gen"

SECTIONS = [
    (0x02000000, ROOT / "out" / "raw" / "arm9_section_0_02000000.bin"),
    (0x01FF8000, ROOT / "out" / "raw" / "arm9_section_1_01ff8000.bin"),
    (0x027E0000, ROOT / "out" / "raw" / "arm9_section_2_027e0000.bin"),
]

SYMBOL = re.compile(r"\b((?:DAT|PTR|UNK|_DAT|__DAT)_[0-9a-fA-F]{8})\b")
DEREF = re.compile(r"\*\s*((?:DAT|PTR|UNK|_DAT|__DAT)_[0-9a-fA-F]{8})\b")
# The definition line: a return type, the FUN_ name, and an argument list.
DEFN = re.compile(
    r"^([A-Za-z_][A-Za-z0-9_ \*]*?)\s*\n?(FUN_[0-9a-f]{8}|thunk_FUN_[0-9a-f]{8})"
    r"\s*\(([^)]*)\)\s*$",
    re.M)


def load_image():
    blobs = []
    for base, path in SECTIONS:
        if path.exists():
            blobs.append((base, path.read_bytes()))
    return blobs


def word_at(blobs, addr):
    for base, blob in blobs:
        off = addr - base
        if 0 <= off + 4 <= len(blob):
            return struct.unpack_from("<I", blob, off)[0]
    return None


def sources():
    for directory in (DECOMP, DECOMP_ITCM):
        if directory.exists():
            for path in sorted(directory.glob("*.c")):
                yield path


def main() -> int:
    GEN.mkdir(parents=True, exist_ok=True)
    blobs = load_image()

    used = defaultdict(int)
    dereferenced = set()
    protos = {}
    files = list(sources())

    for path in files:
        text = path.read_text(encoding="utf-8", errors="replace")
        for name in SYMBOL.findall(text):
            used[name] += 1
        for name in DEREF.findall(text):
            dereferenced.add(name)
        match = DEFN.search(text)
        if match:
            ret, name, args = match.groups()
            ret = " ".join(ret.split())
            args = " ".join(args.split()) or "void"
            protos[name] = "%s %s(%s);" % (ret, name, args)

    # ---- types -----------------------------------------------------------
    (OUT / "include").mkdir(parents=True, exist_ok=True)
    (OUT / "include" / "ghidra_types.h").write_text(
        TYPES_H, encoding="utf-8")

    # ---- prototypes ------------------------------------------------------
    lines = ["/* Generated by tools/gen_decomp_build.py - do not edit. */",
             "#ifndef LSW2_DECOMP_PROTOS_H", "#define LSW2_DECOMP_PROTOS_H",
             '#include "ghidra_types.h"', ""]
    for name in sorted(protos):
        lines.append(protos[name])
    lines += ["", "#endif"]
    (GEN / "protos.h").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # ---- DAT symbols -----------------------------------------------------
    both = []
    lines = ["/* Generated by tools/gen_decomp_build.py - do not edit.",
             " *",
             " * Ghidra names a literal-pool word by its POOL ADDRESS. A symbol",
             " * that the bodies dereference is emitted pointer-shaped; one only",
             " * ever read is emitted value-shaped. Where the image has no word",
             " * at the address the symbol is left undefined so the compiler",
             " * says so rather than inventing a zero.",
             " */",
             "#ifndef LSW2_DECOMP_DAT_H", "#define LSW2_DECOMP_DAT_H",
             '#include "ghidra_types.h"', ""]
    missing = 0
    for name in sorted(used):
        addr = int(name.split("_")[-1], 16)
        value = word_at(blobs, addr)
        if value is None:
            missing += 1
            continue
        if name in dereferenced:
            lines.append("#define %s ((void *)(uintptr_t)0x%08Xu)" % (name, value))
        else:
            lines.append("#define %s (*(u32 *)(uintptr_t)0x%08Xu)" % (name, addr))
    lines += ["", "#endif"]
    (GEN / "dat.h").write_text("\n".join(lines) + "\n", encoding="utf-8")

    print("decompiled sources        %d" % len(files))
    print("prototypes recovered      %d" % len(protos))
    print("DAT symbols referenced    %d" % len(used))
    print("  dereferenced (pointer)  %d" % len(dereferenced))
    print("  outside the image       %d" % missing)
    print()
    print("wrote %s" % (GEN.relative_to(ROOT)))
    return 0


TYPES_H = r"""/* The types Ghidra's decompiler emits, plus the DS memory map.
 *
 * Generated support, not generated code: this file is written by hand and
 * copied unchanged by tools/gen_decomp_build.py.
 *
 * THE WHOLE APPROACH RESTS ON ONE FACT: every DS region can be mapped at its
 * native address on the host, so the decompiled bodies' raw pointer arithmetic
 * on DS addresses works with no rewriting. See lsw2_decomp_map().
 */

#ifndef LSW2_GHIDRA_TYPES_H
#define LSW2_GHIDRA_TYPES_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

typedef uint8_t undefined;
typedef uint8_t undefined1;
typedef uint16_t undefined2;
typedef uint32_t undefined4;
typedef uint64_t undefined8;
typedef uint8_t byte;
typedef int8_t sbyte;
typedef uint16_t ushort;
typedef uint32_t uint;
typedef uint64_t ulong;
typedef uint64_t ulonglong;
typedef int64_t longlong;
typedef uint8_t bool1;
/* `code` is Ghidra's type for MACHINE CODE, so it must be a FUNCTION type,
 * not void. Indirect targets are declared `code *pcVar1;` and called as
 * `(*pcVar1)(...)`; as void that is a dereference of void. */
typedef undefined4 code();
typedef uint32_t u32;
typedef uint16_t u16;
typedef uint8_t u8;

/* Ghidra emits these for the ARM condition-flag helpers on occasion. */
#define CONCAT11(a, b) ((uint16_t)(((uint16_t)(uint8_t)(a) << 8) | (uint8_t)(b)))
#define CONCAT12(a, b) ((uint32_t)(((uint32_t)(uint8_t)(a) << 16) | (uint16_t)(b)))
#define CONCAT13(a, b) ((uint32_t)(((uint32_t)(uint8_t)(a) << 24) | ((b) & 0xFFFFFFu)))
#define CONCAT22(a, b) ((uint32_t)(((uint32_t)(uint16_t)(a) << 16) | (uint16_t)(b)))
#define CONCAT44(a, b) ((uint64_t)(((uint64_t)(uint32_t)(a) << 32) | (uint32_t)(b)))
#define SUB84(x, n)    ((uint32_t)((uint64_t)(x) >> ((n) * 8)))
#define SUB41(x, n)    ((uint8_t)((uint32_t)(x) >> ((n) * 8)))

/* The DS regions, at their real addresses. */
#define LSW2_ITCM_BASE   0x01FF8000u
#define LSW2_ITCM_SIZE   0x00008000u
#define LSW2_MAIN_BASE   0x02000000u
#define LSW2_MAIN_SIZE   0x00400000u
#define LSW2_MAIN_WINDOW 0x01000000u
#define LSW2_DTCM_BASE   0x027E0000u
#define LSW2_DTCM_SIZE   0x00004000u
#define LSW2_WRAM_BASE   0x03000000u
#define LSW2_WRAM_SIZE   0x00008000u
#define LSW2_PAL_BASE    0x05000000u
#define LSW2_PAL_SIZE    0x00000800u
#define LSW2_IO_BASE     0x04000000u
#define LSW2_IO_SIZE     0x01000000u
#define LSW2_VRAM_BASE   0x06000000u
#define LSW2_VRAM_SIZE   0x01000000u
#define LSW2_GBA_BASE    0x08000000u
#define LSW2_GBA_SIZE    0x02000000u
#define LSW2_OAM_BASE    0x07000000u
#define LSW2_OAM_SIZE    0x00000800u

/* Reserve every region at its DS address and load the ARM9 sections into it.
 * Returns false if any reservation fails, which would mean this host cannot
 * run the port this way and the whole approach needs revisiting. */
bool lsw2_decomp_map(const char *root);

#endif /* LSW2_GHIDRA_TYPES_H */
"""


if __name__ == "__main__":
    raise SystemExit(main())
