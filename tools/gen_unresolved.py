"""Declare Ghidra's unresolved-storage markers, and record who reads them.

WHAT THEY ARE. When the decompiler cannot work out where a value lives it names
the location instead of the variable:

    stack0xffffffcc      a stack slot it could not attach to a local
    register0x00000054   a register it could not attach to anything

157 files reference one. They are undeclared, so those files do not compile, so
each function becomes an aborting stub and the port dies on it - which is how
FUN_01FFD55C presented.

DECLARING THEM IS NOT THE SAME AS FIXING THEM. A file that compiles because its
unresolved storage is now a zero-initialised global is not a faithful
translation; it is a wrong one that runs. That is strictly worse than a stub
UNLESS it is recorded, because a stub at least says something.

So both happen: the names are declared so the code builds, and every function
that touches one is added to the unfaithful list, which wraps it and reports at
exit whether the game actually reached it. That is the same treatment as
unaff_/in_/extraout_, for the same reason - 70 functions were in that state and
the game's initialisation touched two.

The count here is the honest measure of how much of the port is running on
values Ghidra could not account for.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
DIRS = [ROOT / "out/ghidra/decomp/c", ROOT / "out/ghidra/decomp_itcm/c"]
MARK = re.compile(r"\b((?:stack|register)0x[0-9a-fA-F]+)\b")


def main() -> int:
    names, users = set(), set()
    for d in DIRS:
        if not d.exists():
            continue
        for p in d.glob("FUN_*.c"):
            hits = set(MARK.findall(p.read_text(encoding="utf-8",
                                                errors="replace")))
            if hits:
                names |= hits
                users.add(p.stem)

    out = [
        "/* Generated by tools/gen_unresolved.py - do not edit.",
        " *",
        " * Ghidra's markers for storage it could not resolve. Declaring them",
        " * makes the code build; it does NOT make it correct, which is why",
        " * every function touching one is on the unfaithful list and reports",
        " * itself when reached. See the generator.",
        " */",
        "#ifndef LSW2_UNRESOLVED_H",
        "#define LSW2_UNRESOLVED_H",
        '#include "ghidra_types.h"',
        "",
    ]
    for n in sorted(names):
        out.append("extern undefined4 %s;" % n)
    out += ["", "#endif"]
    (ROOT / "recomp/decomp/gen/unresolved.h").write_text(
        "\n".join(out) + "\n", encoding="utf-8")

    defs = [
        "/* Generated by tools/gen_unresolved.py - do not edit.",
        " * Zero, and counted as a lie. See the header. */",
        '#include "ghidra_intrinsics.h"',
        '#include "unresolved.h"',
        "",
    ]
    for n in sorted(names):
        defs.append("undefined4 %s;" % n)
    (ROOT / "recomp/decomp/src/unresolved.c").write_text(
        "\n".join(defs) + "\n", encoding="utf-8")

    (ROOT / "out/work/unresolved_users.txt").write_text(
        "\n".join(sorted(users)) + "\n", encoding="utf-8")

    print("unresolved storage markers %d" % len(names))
    print("functions reading one      %d" % len(users))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
