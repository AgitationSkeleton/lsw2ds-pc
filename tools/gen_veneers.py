"""Generate tail-call veneers from the INSTRUCTIONS, not the decompiled text.

WHAT A VENEER IS. Two or three instructions that load an address and branch to
it, preserving every register so the caller's arguments arrive at the target
untouched:

    E59FC000  ldr r12, [pc, #0]
    E12FFF1C  bx  r12
    020CCC90  <- the target, a literal

Ghidra types that `void f(void)` because those instructions touch no argument
registers, so the caller's arguments are dropped on the floor. The host has to
provide a forwarder instead.

WHY THIS READS INSTRUCTIONS AND NOT GHIDRA'S C. The first version of this tool
matched on the decompiled body and checked for pointer stores to decide whether
a veneer was "pure". FUN_020CCCDC slipped through:

    E59FC004  ldr r12, [pc, #4]
    E3A03000  mov r3, #0        <- SETS AN ARGUMENT REGISTER
    E12FFF1C  bx  r12

Ghidra had already dropped the `mov r3, #0` from its output, so there was
nothing in the C to notice, and the generated forwarder passed the caller's r3
straight through where the hardware forces it to zero. A wrong value, silently,
in code that looked right.

Reading the instructions cannot miss it: anything between the load and the
branch is either an immediate register set - which the forwarder reproduces -
or something this tool does not understand, in which case the function is left
alone rather than guessed at.
"""

from __future__ import annotations

import json
import pathlib
import struct

ROOT = pathlib.Path(__file__).resolve().parents[1]
SECTIONS = [(0x02000000, ROOT / "out/raw/arm9_section_0_02000000.bin"),
            (0x01FF8000, ROOT / "out/raw/arm9_section_1_01ff8000.bin")]
INDEXES = [ROOT / "out/ghidra/decomp/index.jsonl",
           ROOT / "out/ghidra/decomp_itcm/index.jsonl"]
MAX_BODY = 6  # instructions; a veneer is never longer than this


def imm_of(w):
    rot = ((w >> 8) & 0xF) * 2
    v = w & 0xFF
    return ((v >> rot) | (v << (32 - rot))) & 0xFFFFFFFF if rot else v


def main() -> int:
    blobs = [(b, p.read_bytes()) for b, p in SECTIONS if p.exists()]

    def word(a):
        for base, d in blobs:
            o = a - base
            if 0 <= o + 4 <= len(d):
                return struct.unpack_from("<I", d, o)[0]
        return None

    # Every function Ghidra knows, so a veneer can be named as callers name it.
    names, defined = {}, set()
    for idx in INDEXES:
        if not idx.exists():
            continue
        for line in idx.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            r = json.loads(line)
            names[int(r["address"], 16)] = r["name"]
            defined.add(r["name"])

    rows, skipped = [], []
    for addr, name in sorted(names.items()):
        # Walk the body looking for: an optional run of immediate register
        # sets, a pc-relative load of the target, and a bx to it.
        target_reg, target = None, None
        presets = []
        ok = False
        for i in range(MAX_BODY):
            w = word(addr + i * 4)
            if w is None:
                break
            # LDR rD, [pc, #imm]
            if (w & 0x0FFF0000) == 0x059F0000:
                rd = (w >> 12) & 0xF
                lit = addr + i * 4 + 8 + (w & 0xFFF)
                v = word(lit)
                if v is None:
                    break
                target_reg, target = rd, v
                continue
            # MOV rD, #imm - a register the veneer forces
            if (w & 0x0FEF0000) == 0x03A00000:
                presets.append(((w >> 12) & 0xF, imm_of(w)))
                continue
            # BX rD - the branch
            if (w & 0x0FFFFFF0) == 0x012FFF10:
                if (w & 0xF) == target_reg and target is not None:
                    ok = True
                break
            break  # anything else and this is not a veneer

        if not ok:
            continue
        tname = names.get(target & ~1)
        if tname is None:
            skipped.append((name, target))
            continue
        if tname == name:
            continue
        # A register the veneer forces must not also be forwarded.
        forced = {r: v for r, v in presets if r <= 3}
        # The file is named for the ADDRESS; the function inside may be named
        # for its target (thunk_FUN_...). The build excludes by file stem, so
        # both are carried - getting this wrong links two definitions of the
        # same symbol.
        rows.append((name, tname, target, forced, "FUN_%08x" % addr))

    out = [
        "/* Generated by tools/gen_veneers.py - do not edit.",
        " * Read from the instructions; see that file for why not from the C.",
        " */",
        '#include "ghidra_intrinsics.h"',
        "",
        "typedef undefined4 (*lsw2_any)(undefined4, undefined4, undefined4,",
        "                               undefined4);",
        "",
    ]
    for t in sorted({r[1] for r in rows}):
        out.append("undefined4 %s();" % t)
    out.append("")
    seen = set()
    emitted = 0
    for name, tname, target, forced, _stem in rows:
        if name in seen:
            continue
        seen.add(name)
        emitted += 1
        note = ", forcing " + ", ".join("r%d=0x%X" % (r, v)
                                        for r, v in sorted(forced.items())) \
            if forced else ""
        out.append("/* %s -> 0x%08X%s */" % (name, target, note))
        out.append("undefined4 %s(undefined4 a, undefined4 b, undefined4 c,"
                   " undefined4 d) {" % name)
        for r, v in sorted(forced.items()):
            out.append("    %s = 0x%Xu;  /* the veneer sets this itself */"
                       % ("abcd"[r], v))
        out.append("    return ((lsw2_any)%s)(a, b, c, d);" % tname)
        out.append("}")
        out.append("")
    (ROOT / "recomp/decomp/src/veneers.c").write_text("\n".join(out),
                                                      encoding="utf-8")

    stems = sorted({r[4] for r in rows})
    (ROOT / "config/veneers.txt").write_text(
        "# Tail-call veneers, host-generated so they forward their arguments\n"
        "# and reproduce any register the veneer itself forces.\n"
        "# See tools/gen_veneers.py.\n" + "\n".join(stems) + "\n",
        encoding="utf-8")

    # The same pairs, for Ghidra: giving a veneer its target's signature is
    # what makes CALLERS pass the arguments. Without it Parameter ID types the
    # veneer (void) - correctly for two instructions that touch no registers -
    # and strips the arguments from every call site.
    (ROOT / "out/work/veneer_pairs.txt").write_text(
        "\n".join("%s %08x" % (r[4][4:], r[2] & ~1)
                     for r in rows) + "\n",
        encoding="utf-8")

    print("veneers found in the instructions %d" % emitted)
    print("  forcing a register themselves    %d"
          % sum(1 for r in rows if r[3]))
    if skipped:
        print("  target has no function           %d" % len(skipped))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
