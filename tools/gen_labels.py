"""Define the LAB_ symbols Ghidra references but never declares.

WHAT THEY ARE. Where a constant happens to coincide with an address Ghidra has
labelled, it writes the label instead of the number:

    if (param_1 == 0) {
      puVar2 = &LAB_00005000;      /* the constant 0x5000 */
    } else {
      puVar2 = (undefined1 *)0x1000;
    }
    FUN_020ce3b4(0xf000, (uint)puVar2);

Both arms are plainly flag values for the same call - 0x5000 and 0x1000 - and
one of them arrived as a label purely because something is labelled at that
address. The C does not compile, because the label is referenced and never
declared.

WHY THIS MATTERS MORE THAN IT LOOKS. A file that fails to compile does not
vanish quietly: the function becomes an aborting stub, and the port dies at it
with a message. FUN_020DD930 was exactly that, and finding it took several
rounds because the stub's own diagnostic was crashing before it could print.

THE DEFINITION IS THE OBVIOUS ONE, and it is what Ghidra means: a label names a
location, so the symbol is the byte at that address and `&LAB_x` is the address
itself. Defining it any other way would change the value the game computes.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
DIRS = [ROOT / "out/ghidra/decomp/c", ROOT / "out/ghidra/decomp_itcm/c"]
# A LAB_ NAME IS EITHER A VALUE OR A GOTO LABEL, AND DEFINING THE WRONG ONE
# BREAKS THE FILE. Ghidra writes both:
#
#     puVar2 = &LAB_00005000;    <- a value; needs defining
#   LAB_02000f68:                <- a goto label; must NOT be a macro
#
# Turning the second into a macro rewrites the label definition itself and
# the file stops compiling - which is what took 111 previously-working
# files out of the build.
TAKEN = re.compile(r"&\s*(LAB_[0-9a-fA-F]{8})\b")
DEFINED_HERE = re.compile(r"^\s*(LAB_[0-9a-fA-F]{8})\s*:", re.M)


def main() -> int:
    used = set()
    files = 0
    for d in DIRS:
        if not d.exists():
            continue
        for p in d.glob("FUN_*.c"):
            text = p.read_text(encoding="utf-8", errors="replace")
            hits = set(TAKEN.findall(text)) - set(DEFINED_HERE.findall(text))
            if hits:
                files += 1
                used |= hits

    out = [
        "/* Generated by tools/gen_labels.py - do not edit.",
        " *",
        " * Ghidra references these but never declares them. A label names a",
        " * location, so each is the byte at its address and &LAB_x is that",
        " * address - which is what the surrounding code uses it as.",
        " */",
        "#ifndef LSW2_LABELS_H",
        "#define LSW2_LABELS_H",
        '#include "ghidra_types.h"',
        "",
    ]
    for name in sorted(used):
        addr = int(name.split("_")[-1], 16)
        out.append("#define %s (*(undefined1 *)(uintptr_t)0x%08Xu)"
                   % (name, addr))
    out += ["", "#endif"]
    (ROOT / "recomp/decomp/gen/labels.h").write_text("\n".join(out) + "\n",
                                                     encoding="utf-8")
    print("label symbols defined %d  (referenced in %d file(s))"
          % (len(used), files))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
