"""Count calls to named functions without touching a line of decompiled C.

WHY THIS EXISTS. The port runs the cartridge's own frame loop and reports
"cartridge words read 0, GX words written 0" - it is executing, and doing
nothing. Reading the decompiled sources can narrow that down but cannot settle
it: FUN_02001480 has three early returns and a vtable dispatch, and which path
it takes depends on state the game builds at runtime.

The answer is to ask the running program. Each traced function is compiled under
a renamed symbol via -D and a generated wrapper takes the real name, counts the
call and passes straight through - the same mechanism already used for the
functions that read unaccounted registers, which is how "68 might be wrong"
became a two-item list.

Nothing in out/ghidra is edited, the call sites are untouched, and turning a
trace off is deleting a line from config/traced_functions.txt.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]


DIRS = [ROOT / "out/work/patched",
        ROOT / "out/ghidra/decomp/c",
        ROOT / "out/ghidra/decomp_itcm/c"]

# Ghidra writes the signature on one line or wrapped over two; take everything
# between the name's opening bracket and the matching close.
def signature_of(name: str):
    """(return type, parameter list, [argument names]) for a traced function.

    Falls back to the old generic four-argument shape only when the source
    cannot be found, and says so, because a silent fallback would reintroduce
    exactly the non-transparency this exists to remove.
    """
    for d in DIRS:
        p = d / (name + ".c")
        if not p.exists():
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"^([A-Za-z_][\w \*]*?)\s*\b%s\s*\(" % re.escape(name),
                      text, re.M)
        if not m:
            continue
        ret = m.group(1).strip()
        # Walk to the matching bracket so nested parens in a parameter type
        # (a function pointer) do not truncate the list.
        i, depth = m.end() - 1, 0
        while i < len(text):
            if text[i] == "(":
                depth += 1
            elif text[i] == ")":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        params = " ".join(text[m.end():i].split())
        if params.strip() in ("", "void"):
            return ret, "void", []
        args, depth, cur = [], 0, ""
        for ch in params:
            if ch == "," and depth == 0:
                args.append(cur)
                cur = ""
                continue
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            cur += ch
        args.append(cur)
        names_out = []
        for a in args:
            w = re.findall(r"[A-Za-z_]\w*", a)
            names_out.append(w[-1] if w else "unnamed")
        return ret, params, names_out
    print("  %s: no source found, falling back to the generic shape" % name)
    return "undefined4", ("undefined4 a, undefined4 b, undefined4 c, "
                          "undefined4 d"), ["a", "b", "c", "d"]


def main() -> int:
    cfg = ROOT / "config/traced_functions.txt"
    if not cfg.exists():
        cfg.write_text("# One function name per line; blank lines and # ignored.\n",
                       encoding="utf-8")
    names = [l.strip() for l in cfg.read_text(encoding="utf-8").splitlines()
             if l.strip() and not l.startswith("#")]

    # A function cannot be both traced and host-replaced or wrapped as
    # unfaithful - only one wrapper may own a name.
    taken = set()
    for other in ("config/host_overrides.txt", "config/unfaithful_wrapped.txt",
                  "config/excluded_functions.txt"):
        p = ROOT / other
        if p.exists():
            taken |= {l.strip() for l in p.read_text(encoding="utf-8").splitlines()
                      if l.strip() and not l.startswith("#")}
    clash = [n for n in names if n in taken]
    names = [n for n in names if n not in taken]

    out = [
        "/* Generated by tools/gen_trace_wrappers.py - do not edit. */",
        '#include "ghidra_intrinsics.h"',
        "",
        "typedef undefined4 (*lsw2_any)(undefined4, undefined4, undefined4,",
        "                               undefined4);",
        "",
        "unsigned long lsw2_trace_hits[%d];" % max(1, len(names)),
        "const char *const lsw2_trace_names[] = {",
    ]
    for n in names:
        out.append('    "%s",' % n)
    out += ["};", "const unsigned lsw2_trace_count = %d;" % len(names), ""]
    # THE WRAPPER MUST HAVE THE FUNCTION'S OWN SIGNATURE, NOT A GENERIC ONE.
    #
    # It used to be `undefined4 f(undefined4 a, b, c, d)` for every traced
    # function, forwarding four arguments through a cast whatever the real
    # arity was. That is not transparent, and a diagnostic that changes the
    # thing it measures is worse than none: adding three traces moved the
    # port's failure from a read fault at 0x1C to an execute fault at 0, and
    # the first suspicion had to be the instrument rather than the program.
    #
    # Ghidra already wrote the signature. Copy it, rename the definition, and
    # forward the parameters by name - then the wrapper is transparent by
    # construction and cannot be the explanation for anything.
    sigs = {}
    for n in names:
        sigs[n] = signature_of(n)
    for n in names:
        ret, params, _args = sigs[n]
        out.append("%s %s_traced(%s);" % (ret, n, params))
    out.append("")
    for i, n in enumerate(names):
        ret, params, args = sigs[n]
        out.append("%s %s(%s) {" % (ret, n, params))
        out.append("    lsw2_trace_hits[%d]++;" % i)
        call = "%s_traced(%s)" % (n, ", ".join(args))
        out.append("    %s;" % call if ret == "void"
                   else "    return %s;" % call)
        out.append("}")
        out.append("")
    out += [
        "LSW2_HOSTCALL void lsw2_report_trace(FILE *to) {",
        "    (void)to;  /* stderr is unusable here - see diag.c */",
        "    if (!lsw2_trace_count) return;",
        '    lsw2_diagf("traced functions:\\n");',
        "    for (unsigned i = 0; i < lsw2_trace_count; i++) {",
        '        lsw2_diagf("  %-16s %lu call(s)%s\\n", lsw2_trace_names[i],',
        "                lsw2_trace_hits[i],",
        '                lsw2_trace_hits[i] ? "" : "   <- NEVER REACHED");',
        "    }",
        "}",
        "",
    ]
    (ROOT / "recomp/decomp/src/trace_wrappers.c").write_text(
        "\n".join(out), encoding="utf-8")
    (ROOT / "config/traced_active.txt").write_text(
        "\n".join(names) + ("\n" if names else ""), encoding="utf-8")

    print("traced functions %d" % len(names))
    if clash:
        print("  skipped, already wrapped elsewhere: %s" % ", ".join(clash))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
