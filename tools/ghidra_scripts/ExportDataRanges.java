/* Export every byte range that is NOT an instruction, as ndsrecomp TOML.
 *
 * WHY. A lifter discovers functions by following calls and branches. When a
 * branch target lands in a literal pool, a jump table or a string, it decodes
 * whatever is there - and arbitrary bytes decode into perfectly legal-looking
 * ARM, because most 32-bit words are a valid instruction. That is how an audit
 * of the LSW2 ARM9 came back reporting 82,946 SWI instructions and 12,630
 * coprocessor ops in a game that issues almost none: not a decoder fault, just
 * data being read as code.
 *
 * ndsrecomp has the mechanism to stop it - [[data_range]] entries mark bytes
 * the finder must never walk into - and our generated config declared none.
 * Ghidra already knows the answer, because its analysis decided what is an
 * instruction and what is not when it produced the listing.
 *
 * SO THIS IS SUBTRACTION, NOT DETECTION. Build the set of bytes covered by
 * instructions, subtract it from initialised memory, and what remains is data
 * by construction. No heuristic, no guessing at prologues, and no opinion of
 * mine in the middle of it.
 *
 * THE ONE HONEST CAVEAT. This is only as good as Ghidra's analysis. Bytes it
 * never disassembled - because nothing reachable pointed at them - look exactly
 * like data here, and if they are really code reached only indirectly, marking
 * them as data would wrongly fence the lifter out. That is why every range
 * carries a note saying which case it is, and why the summary prints how much
 * of the image each case covers: a large "never disassembled" figure means the
 * analysis is incomplete, not that the image is mostly data.
 *
 * Usage:  -postScript ExportDataRanges.java <output.toml>
 */

import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.address.AddressRange;
import ghidra.program.model.address.AddressRangeIterator;
import ghidra.program.model.address.AddressSet;
import ghidra.program.model.address.AddressSetView;
import ghidra.program.model.listing.Data;
import ghidra.program.model.listing.DataIterator;
import ghidra.program.model.listing.Instruction;
import ghidra.program.model.listing.InstructionIterator;
import java.io.PrintWriter;

public class ExportDataRanges extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length == 0) {
            println("usage: ExportDataRanges <output.toml>");
            return;
        }

        /* Everything the loader actually put bytes into. */
        AddressSetView loaded =
            currentProgram.getMemory().getLoadedAndInitializedAddressSet();

        /* Everything Ghidra decided is an instruction. */
        AddressSet code = new AddressSet();
        InstructionIterator ii = currentProgram.getListing().getInstructions(true);
        long ninstr = 0;
        while (ii.hasNext()) {
            if (monitor.isCancelled()) { println("CANCELLED - nothing written."); return; }
            Instruction in = ii.next();
            code.addRange(in.getMinAddress(), in.getMaxAddress());
            ninstr++;
        }

        /* Everything Ghidra decided is typed data - kept separately only so the
         * note can distinguish "known to be data" from "never looked at". */
        AddressSet typed = new AddressSet();
        DataIterator di = currentProgram.getListing().getDefinedData(true);
        while (di.hasNext()) {
            if (monitor.isCancelled()) { println("CANCELLED - nothing written."); return; }
            Data d = di.next();
            typed.addRange(d.getMinAddress(), d.getMaxAddress());
        }

        AddressSet notCode = new AddressSet(loaded);
        notCode.delete(code);

        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by tools/ghidra_scripts/ExportDataRanges.java.\n");
        sb.append("# Byte ranges that are NOT instructions, for ndsrecomp's finder.\n");
        sb.append("# Derived by subtracting Ghidra's instruction coverage from\n");
        sb.append("# initialised memory - see the script header for the caveat.\n\n");

        long nranges = 0, bytesTyped = 0, bytesUnknown = 0;
        AddressRangeIterator ri = notCode.getAddressRanges();
        while (ri.hasNext()) {
            if (monitor.isCancelled()) { println("CANCELLED - nothing written."); return; }
            AddressRange r = ri.next();
            Address min = r.getMinAddress();
            long start = min.getOffset();
            long end = r.getMaxAddress().getOffset() + 1;   /* exclusive */
            long len = end - start;

            boolean isTyped = typed.contains(min);
            if (isTyped) { bytesTyped += len; } else { bytesUnknown += len; }

            sb.append("[[data_range]]\n");
            sb.append(String.format("start = 0x%08X\n", start));
            sb.append(String.format("end   = 0x%08X\n", end));
            sb.append(String.format("note  = \"%s, %d bytes\"\n\n",
                isTyped ? "defined data" : "never disassembled", len));
            nranges++;
        }

        try (PrintWriter w = new PrintWriter(args[0], "UTF-8")) {
            w.print(sb);
        }

        long loadedBytes = loaded.getNumAddresses();
        long codeBytes = code.getNumAddresses();
        println(String.format(
            "ExportDataRanges: %d instructions covering %d bytes of %d loaded "
            + "(%.1f%%)", ninstr, codeBytes, loadedBytes,
            100.0 * codeBytes / loadedBytes));
        println(String.format(
            "ExportDataRanges: %d non-code ranges -> %s", nranges, args[0]));
        println(String.format(
            "ExportDataRanges:   defined data       %d bytes (%.1f%%)",
            bytesTyped, 100.0 * bytesTyped / loadedBytes));
        println(String.format(
            "ExportDataRanges:   never disassembled %d bytes (%.1f%%)"
            + "  <- if this is large, the ANALYSIS is incomplete",
            bytesUnknown, 100.0 * bytesUnknown / loadedBytes));
    }
}
