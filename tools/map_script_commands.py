"""Regenerate config/script_commands.json - the level script's vocabulary.

WHY IT IS A TOOL AND NOT A ONE-OFF. `0x02055E98` dispatches 192 handlers over
`0x020ED928`, and this project has now twice chosen a seam a thing never crossed
because the three command tables in this ROM were being confused with each
other. A generated map is cheaper to trust than a remembered one, and it can
be re-run when a new global is worth tagging - add it to KNOWN and the whole
table is reclassified.

WHAT IT CLASSIFIES BY. For each handler, bounded at its own return, the known
globals its literal pool mentions and the known functions it calls. That is a
coarse net on purpose: it names the 28 handlers worth reading, rather than
pretending to decompile all 192.

THE BOUND MATTERS. An unbounded scan runs past each function's end into the next
and reports handlers as doing things their neighbours do - it produced eleven
false dialog-raisers before the return check was added. Every bad scan this
project has made had the same cause.
"""

from __future__ import annotations

import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IMAGE = ROOT / "out" / "raw" / "arm9_section_0_02000000.bin"
OUT = ROOT / "config" / "script_commands.json"
BASE = 0x02000000
TABLE = 0x020ED928
COUNT = 192

KNOWN = {
    0x0210930C: "level root", 0x02102900: "state manager",
    0x02104D90: "save flags", 0x0210794C: "netplay obj",
    0x02106D90: "wireless owner", 0x021027F8: "input/counts",
    0x0210B348: "wireless mgr", 0x02107890: "customization",
    0x021092F4: "camera mgr", 0x02106FD8: "appearance rec",
    0x027E02A8: "game-state bits", 0x0210BF40: "host table",
    0x02104D84: "mode block",
}

CALLS = {
    0x020601AC: "raise dialog", 0x02086204: "flag test",
    0x020861BC: "flag set", 0x0205ECC4: "state request",
    0x020B04F0: "net send", 0x02091B88: "appearance apply",
    0x02093C6C: "pause bits",
}

MEANINGS = {
    168: "raise a dialog; id = arg[0] + 0x2AE",
    44: "if flag N then set widget A else B; the console's refusal branch",
    100: "set [0x02104D84+0xC] bit 0 and actor+0x5D6 = 1",
    101: "clear that bit and actor+0x5D6 = 0",
}


def main() -> int:
    if not IMAGE.exists():
        print(f"skipped: {IMAGE} is not extracted")
        return 0
    data = IMAGE.read_bytes()

    def rd(a: int) -> int:
        return struct.unpack_from("<I", data, a - BASE)[0]

    def is_ret(w: int) -> bool:
        if (w & 0x0FFF0000) == 0x08BD0000 and (w & 0x8000):
            return True
        return (w & 0x0FFFFFFF) == 0x012FFF1E

    out = {
        "note": "LSW2 level-script command table, dispatched by 0x02055E98 over "
                "0x020ED928. Generated by tools/map_script_commands.py.",
        "dispatcher": "0x02055E98",
        "table": "0x020ED928",
        "count": COUNT,
        "commands": {},
    }

    for i in range(COUNT):
        h = rd(TABLE + i * 4)
        if not (0x02040000 <= h < 0x02060000):
            continue
        tags, calls = set(), set()
        for k in range(90):
            a = h + k * 4
            w = rd(a)
            if (w >> 24) & 0x0F == 0x0B:
                imm = w & 0xFFFFFF
                if imm & 0x800000:
                    imm -= 0x1000000
                t = a + 8 + (imm << 2)
                if t in CALLS:
                    calls.add(CALLS[t])
            if w in KNOWN:
                tags.add(KNOWN[w])
            if is_ret(w):
                break
        entry = {"handler": f"0x{h:08X}"}
        if tags:
            entry["touches"] = sorted(tags)
        if calls:
            entry["calls"] = sorted(calls)
        if i in MEANINGS:
            entry["meaning"] = MEANINGS[i]
        out["commands"][str(i)] = entry

    OUT.write_text(json.dumps(out, indent=2), encoding="utf-8")
    named = sum(1 for e in out["commands"].values()
                if "touches" in e or "calls" in e)
    print(f"{len(out['commands'])} handlers, {named} touching a known global "
          f"or function -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
